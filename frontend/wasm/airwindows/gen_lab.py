#!/usr/bin/env python3
"""Writes lab_entries.inc (what aw_wasm.cpp compiles for the Lab build) and ../../src/lib/dsp/awLabInfo.ts (names, groups and
descriptions for the dropdown) from the plugin sources in src/autogen_airwin and Chris Johnson's description list (what.txt)."""
import re, os, json
here = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(here, "src/autogen_airwin")
GROUPS = [
 ("EQs", "Air4 AngleEQ AverMatrix Baxandall3 BezEQ4 BiquadStack Energy2 FatEQ Hull2 Parametric PearEQ PearLiteEQ ResEQ2 SmoothEQ3"),
 ("Biquad and sweepable filters", "AngleFilter Aura Biquad2 BiquadDouble BiquadHiLo BiquadNonLin BiquadOneHalf BiquadPlus BiquadTriple Hermepass Highpass2 Holt2 HypersonX Infrasonic Lowpass2 Pafnuty"),
 ("X filters (retro sampler)", "XBandpass XHighpass XLowpass XNotch XRegion"),
 ("Y filters (soft to nasty)", "YBandpass YHighpass YLowpass YNotBandpass YNotHighpass YNotLowpass YNotNotch YNotch"),
 ("Z filters (Emu e6400 style)", "ZAcidLowpass ZBandpass ZBandpass2 ZHighpass ZHighpass2 ZLowpass ZLowpass2 ZNotch ZNotch2 ZRegion2"),
 ("Cleanup", "DeBess DeBez DeCrackle DeEss DeHiss DeNoise DeRez3 DeRez5 HipCrush"),
 ("Dither and wordlength", "BuildATPDF Dark HighGlossDither"),
 ("Tone, dynamics and space", "BeziComp BitDualPan Crystal FathomFive Galactic3 Hypersoft Overheads Pressure5 SlewSonic"),
]
group_of = {n: g for g, ns in GROUPS for n in ns.split()}
names = sorted(group_of)
desc = {}
for line in open(os.path.join(here, "airwindows-descriptions.txt"), encoding="utf-8"):
    m = re.match(r"^(\w+) (.*?)(?:\[coll=([^\]]*)\])?\s*$", line)
    if m and m.group(1) in group_of and m.group(1) not in desc: desc[m.group(1)] = (m.group(2).strip(), (m.group(3) or "").strip())
FALLBACK = {"BezEQ4": ("is the newest of the BezEQ shelving EQs (BezEQ3 is four vivid, unified bands). The supplied list has no description for it yet.", "")}
for k, v in FALLBACK.items(): desc.setdefault(k, v)
inc = []
for n in names:
    h = open(os.path.join(SRC, n + ".h")).read()
    k = int(re.search(r"kNumParameters\s*=\s*(\d+)", h).group(1))
    inc.append((n, k))
with open(os.path.join(here, "lab_entries.inc"), "w") as f:
    f.write("// generated by gen_lab.py: do not edit\n")
    for n, _ in inc: f.write(f'#include "autogen_airwin/{n}.h"\n')
    for n, _ in inc: f.write(f"static Base *mk{n}() {{ return new airwinconsolidated::{n}::{n}(0); }}\n")
    f.write("static const Entry kEntries[] = {\n" + "".join(f'  {{"{n}", {k}, mk{n}}},\n' for n, k in inc) + "};\n")
files = " ".join(f"src/autogen_airwin/{n}.cpp src/autogen_airwin/{n}Proc.cpp" for n, _ in inc)
open(os.path.join(here, "lab_files.txt"), "w").write(files + "\n")
out = os.path.join(here, "../../src/lib/dsp/awLabInfo.ts")
with open(out, "w") as f:
    f.write("// Generated by wasm/airwindows/gen_lab.py from Chris Johnson's descriptions (airwindows.com). Do not edit by hand.\n")
    f.write("export interface AwInfo { name: string; group: string; blurb: string; recommended: boolean }\n")
    f.write("export const AW_GROUPS: string[] = " + json.dumps([g for g, _ in GROUPS]) + ";\n")
    f.write("export const AW_INFO: Record<string, AwInfo> = {\n")
    for n in names:
        b, c = desc.get(n, ("", ""))
        f.write(f"  {json.dumps(n)}: {{ name: {json.dumps(n)}, group: {json.dumps(group_of[n])}, blurb: {json.dumps(b)}, recommended: {json.dumps('Recommended' in c)} }},\n")
    f.write("};\n")
print(len(names), "plugins;", sum(1 for n in names if n not in desc), "without a description:", [n for n in names if n not in desc])
