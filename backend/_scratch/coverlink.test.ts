import { parseCoverLink } from "../src/lib/coverLink";
let bad = 0; const t = (n: string, ok: boolean) => { console.log((ok ? "ok   " : "FAIL ") + n); if (!ok) bad++; };
const url = (s: unknown) => { const r = parseCoverLink(s); return r.ok ? r.url : "ERR"; };
t("https accepted", url("https://i.imgur.com/abc.jpg") === "https://i.imgur.com/abc.jpg");
t("http accepted", url("http://example.org/a.png") === "http://example.org/a.png");
t("trimmed", url("  https://example.org/a.png  ") === "https://example.org/a.png");
t("empty and null clear", url("") === null && url("   ") === null && url(null) === null && url(undefined) === null);
t("own uploads accepted", url("/uploads/cover-1.png") === "/uploads/cover-1.png");
t("traversal refused", url("/uploads/../etc/passwd") === "ERR");
t("javascript refused", url("javascript:alert(1)") === "ERR");
t("data refused", url("data:image/png;base64,AAAA") === "ERR");
t("ftp and file refused", url("ftp://x.org/a.png") === "ERR" && url("file:///etc/passwd") === "ERR");
t("relative elsewhere refused", url("/admin/users") === "ERR" && url("images/a.png") === "ERR");
t("spaces refused", url("https://x.org/a b.png") === "ERR");
t("credentials refused", url("https://u:p@x.org/a.png") === "ERR");
t("no dot host refused", url("https://intranet/a.png") === "ERR");
t("too long refused", url("https://x.org/" + "a".repeat(600)) === "ERR");
t("non-text refused", url(5) === "ERR" && url({}) === "ERR");
t("error is human", (() => { const r = parseCoverLink("nope"); return !r.ok && r.error.includes("https://"); })());
process.exit(bad ? 1 : 0);
