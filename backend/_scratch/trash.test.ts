import { canRestore, daysLeft, trashCutoff } from "../src/lib/trash.js";
import { csvCell, csvRow } from "../src/lib/csv.js";
import { auditWhere } from "../src/lib/auditFilter.js";
import { mergeInbox } from "../src/lib/inbox.js";
import assert from "node:assert/strict";
const now = Date.parse("2026-10-13T12:00:00Z");
assert.equal(canRestore({ isDeleted: true, deletedAt: new Date(now - 29 * 86400000) }, now), true);
assert.equal(canRestore({ isDeleted: true, deletedAt: new Date(now - 31 * 86400000) }, now), false);
assert.equal(canRestore({ isDeleted: true, deletedAt: null }, now), false);
assert.equal(canRestore({ isDeleted: false, deletedAt: new Date(now) }, now), false);
assert.equal(daysLeft(new Date(now - 29.5 * 86400000), now), 1);
assert.equal(daysLeft(new Date(now - 40 * 86400000), now), 0);
assert.equal(+trashCutoff(now), now - 30 * 86400000);
assert.equal(csvCell("a,b"), '"a,b"'); assert.equal(csvCell('say "hi"'), '"say ""hi"""'); assert.equal(csvCell("=1+1"), "'=1+1"); assert.equal(csvCell(null), ""); assert.equal(csvCell(5), "5");
assert.equal(csvRow(["x", "y,z"]), 'x,"y,z"');
assert.deepEqual(auditWhere({}), {});
const w: any = auditWhere({ q: "del", actor: "Tachy", from: "2026-10-01", to: "2026-10-02" });
assert.equal(w.AND.length, 3); assert.equal(+w.AND[2].createdAt.lt, Date.parse("2026-10-03T00:00:00Z")); assert.equal(+w.AND[2].createdAt.gte, Date.parse("2026-10-01T00:00:00Z"));
assert.equal((auditWhere({ from: "bad" }) as any).AND, undefined);
const it = (kind: any, at: number) => ({ kind, id: at, title: "", who: "", at, to: "" });
assert.deepEqual(mergeInbox([[it("join", 3)], [it("reward", 1), it("submission", 2)]]).map((x) => x.at), [1, 2, 3]);
assert.equal(mergeInbox([[it("join", 1), it("join", 2)]], 1).length, 1);
console.log("ok");
